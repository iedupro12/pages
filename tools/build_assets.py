#!/usr/bin/env python3
"""Rebuild js/assets-data.js from the PNG files in ./assets.

Run this after adding or replacing character images:
    pip install pillow
    python3 tools/build_assets.py

bird.png and bubble.png are the fixed theme pieces. Every other PNG
(c1.png, c2.png, ...) is treated as a character and may be picked at random.
Images are cropped to their visible area, stored as WebP data URIs, so the
page also works when opened straight from disk (file://) without tainting
the canvas, which keeps PNG export working.
"""
import base64, io, json, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets")
OUT = os.path.join(ROOT, "js", "assets-data.js")
FIXED = {"bird", "bubble"}


def pack(path):
    im = Image.open(path).convert("RGBA")
    box = im.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
    crop = im.crop(box)
    buf = io.BytesIO()
    crop.save(buf, "WEBP", quality=94, method=6, alpha_quality=100)
    uri = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
    return {"src": uri, "x": box[0], "y": box[1], "w": crop.width, "h": crop.height,
            "frameW": im.width, "frameH": im.height}


def main():
    names = sorted(f[:-4] for f in os.listdir(SRC) if f.lower().endswith(".png"))
    data = {"bird": None, "bubble": None, "characters": {}}
    for n in names:
        item = pack(os.path.join(SRC, n + ".png"))
        if n in FIXED:
            data[n] = item
        else:
            data["characters"][n] = item
    if not data["bird"] or not data["bubble"] or not data["characters"]:
        sys.exit("assets folder needs bird.png, bubble.png and at least one character png")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// generated by tools/build_assets.py - do not edit by hand\n")
        f.write("window.CARD_ASSETS = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB,", len(data["characters"]), "characters")


if __name__ == "__main__":
    main()
